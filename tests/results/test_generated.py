"""Plan 2 Task 16: the committed RQ1/RQ2 results regenerate byte-identically, carry the one
wording disclaimer, have both figure formats, and leave the P-RQ1 output untouched."""

import subprocess
from pathlib import Path

import pytest

from aideleg.config import ROOT
from aideleg.results import common, rq1, rq2

pytestmark = pytest.mark.data

RQ1_DIR, RQ2_DIR = ROOT / "docs/results/rq1", ROOT / "docs/results/rq2"
FIG_DIR = ROOT / "docs/paper/figures"
CONFIRMATORY = ("confirmatory_rq1.json", "confirmatory_rq1.md", "confirmatory_rq1.log",
                "confirmatory_rq1.attempt")
HANDOFF = ("RQ1 robustness rows R10, R22–R28, R31, R36–R38 are reported in Plan 4, through "
           "these builders and estimators; R28's r4/r5 country parts use Plan 4's own "
           "construction, because r4 and r5 publish no country usage index or GWA rows")


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True,
                          text=True).stdout.strip()


def _text_files(d: Path) -> dict[str, bytes]:
    return {p.name: p.read_bytes() for p in sorted(d.iterdir())
            if p.suffix in (".md", ".csv") and not p.name.startswith("confirmatory_rq1")}


def test_results_docs_up_to_date(tmp_path):
    o1, o2, figs = tmp_path / "rq1", tmp_path / "rq2", tmp_path / "figs"
    assert rq1.main(["--anatomy", "--geography", "--confirmatory", "--out", str(o1),
                     "--fig-dir", str(figs)]) == 0
    rq2.report(o2, figs)
    for committed, fresh in ((RQ1_DIR, o1), (RQ2_DIR, o2)):
        want, got = _text_files(committed), _text_files(fresh)
        assert sorted(got) == sorted(want)
        stale = [n for n in want if want[n] != got[n]]
        assert not stale, f"stale generated files: {stale}"


def _docs() -> list[Path]:
    return [p for d in (RQ1_DIR, RQ2_DIR) for p in sorted(d.rglob("*.md"))
            if p.name != "confirmatory_rq1.md"]


def test_generated_docs_wording():
    docs = _docs()
    assert {p.name for p in docs} >= {"README.md", "decisions.md", "anatomy.md", "bounds.md"}
    for p in docs:
        text = p.read_text(encoding="utf-8")
        first = text.splitlines()[0]
        assert first.startswith("Generated by `aideleg.results.") and first.endswith(
            "Do not edit by hand."), p
        assert common.WORDING in text, p
        common.check_text(text)  # no FORBIDDEN_PHRASES outside WORDING, no stars


def test_every_figure_has_pdf_and_png():
    pdf = {p.stem for p in FIG_DIR.glob("*.pdf")}
    png = {p.stem for p in FIG_DIR.glob("*.png")}
    assert pdf and pdf == png, sorted(pdf ^ png)


def test_rq1_readme_content():
    text = (RQ1_DIR / "README.md").read_text(encoding="utf-8")
    commit = _git("log", "-1", "--format=%H", "--", "docs/results/rq1/confirmatory_rq1.json")
    assert commit in text
    assert rq1.SPLIT_STATEMENT in text
    assert HANDOFF in text
    for p in sorted(RQ1_DIR.iterdir()):
        if p.name != "README.md":
            assert f"`{p.name}`" in text, p.name


def test_confirmatory_output_untouched():
    commit = _git("log", "-1", "--format=%H", "--", "docs/results/rq1/confirmatory_rq1.json")
    r = subprocess.run(["git", "diff", "--quiet", commit, "--",
                        *[f"docs/results/rq1/{n}" for n in CONFIRMATORY]], cwd=ROOT)
    assert r.returncode == 0
