def test_table_numbers_equal_json(json_path, report):
    data = json.loads(json_path.read_text(encoding="utf-8"))
    out, _, _ = report
    with open(out / "confirmatory_table.csv", newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    expected = [(h, c) for h in ("H1", "H2", "H3", "H4") for c in data["results"][h]["coefs"]]
    assert [(r["hypothesis"], r["coefficient"]) for r in rows] == expected
    for r in rows:
        res = data["results"][r["hypothesis"]]
        c = res["coefs"][r["coefficient"]]
        for key in ("estimate", "se", "ci_low", "ci_high", "p"):
            assert float(r[key]) == c[key], (r["coefficient"], key)
        if r["tested"] == "true":
            assert float(r["p_family"]) == res["p_family"]
            assert float(r["holm_level"]) == data["decisions"][r["hypothesis"]]["level"]
            assert r["status"] == data["decisions"][r["hypothesis"]]["status"]
        else:  # a control is not tested: no status, level or family p beside it
            assert (r["p_family"], r["holm_level"], r["status"]) == ("", "", "")
        assert r["unit"] == rq1.UNITS[r["coefficient"]]
        assert r["df"] == ("" if c["df"] is None else str(c["df"]))
    md = (out / "confirmatory_table.md").read_text(encoding="utf-8")
    assert md.count(data["alpha"]["statement"]) == 1
    assert "*" not in "".join(x for x in md.splitlines() if x.startswith("| H"))


def test_attenuation_beside_beta_w_and_gamma(json_path, report):
    data = json.loads(json_path.read_text(encoding="utf-8"))
    out, _, _ = report
    rows = list(csv.DictReader(open(out / "confirmatory_table.csv", encoding="utf-8")))
    for r in rows:
        att = data["results"][r["hypothesis"]]["diagnostics"].get(f"attenuation_{r['coefficient']}")
        if att is None:
            assert r["p13_attenuation"] == ""
        else:
            assert float(r["p13_attenuation"]) == att
    assert {(r["hypothesis"], r["coefficient"]) for r in rows if r["p13_attenuation"]} == {
        ("H1", "log_wage"), ("H3", "error_cost")}


def test_decision_texts_copied_verbatim(json_path, report):
    data = json.loads(json_path.read_text(encoding="utf-8"))
    out, _, _ = report
    md = (out / "decisions.md").read_text(encoding="utf-8")
    for h in ("H1", "H2", "H3", "H4"):
        assert md.count(data["decisions"][h]["text"]) == 1, h
    assert md.count(SPLIT_STATEMENT) == 1
    assert md.splitlines()[0] == "Generated by `aideleg.results.rq1`. Do not edit by hand."
    assert md.count(common.WORDING) == 1
    for note in data["results"]["H2"]["notes"]:
        assert note in md
    assert "C-15" in md
    assert "measured within-task automation rises across releases" in md
    assert "the change in measured within-task automation" in md
    for h in ("H1", "H3"):
        nodes = data["results"][h]["diagnostics"]["structural_drop_nodes"]
        line = ", ".join(f"{k} = {v}" for k, v in nodes.items())
        assert f"{h} structural drop nodes (C-30): {line}" in md


