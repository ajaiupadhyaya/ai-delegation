"""The shared writer of generated results documents (PAP §0.2, spec §6 wording). tmp paths only."""

import polars as pl
import pytest

from aideleg.results import common
from aideleg.rq1.family import _coef_lines
from aideleg.rq1.result import Coef

GEN = "aideleg.results.x"


def test_write_result_doc_rejects_forbidden_and_stars(tmp_path):
    path = tmp_path / "doc.md"
    with pytest.raises(ValueError, match="no effect"):
        common.write_result_doc(path, "T", GEN, [("S", "there is no effect here")])
    with pytest.raises(ValueError, match="job risk"):
        common.write_result_doc(path, "T", GEN, [("S", "Job Risk rises")])
    with pytest.raises(ValueError, match="star"):
        common.write_result_doc(path, "T", GEN, [("S", "| a | b |\n|---|---|\n| x | 0.12** |")])
    assert not path.exists()

    out = common.write_result_doc(path, "T", GEN, [("S", "| a |\n|---|\n| 0.12 |")])
    text = out.read_text(encoding="utf-8")
    assert text.splitlines()[0] == f"Generated by `{GEN}`. Do not edit by hand."
    assert text.count(common.WORDING) == 1
    assert any(p in common.WORDING.lower() for p in common.FORBIDDEN_PHRASES)


def test_write_result_doc_scans_the_title_and_refuses_a_second_wording(tmp_path):
    with pytest.raises(ValueError, match="displacement"):
        common.write_result_doc(tmp_path / "d.md", "Displacement", GEN, [])
    with pytest.raises(ValueError, match="WORDING"):
        common.write_result_doc(tmp_path / "d.md", "T", GEN, [("S", common.WORDING)])


def test_write_csv_keeps_full_precision(tmp_path):
    x = [0.1 + 0.2, 1.852981565286751e-05, -1.6847581030188656]
    path = common.write_csv(pl.DataFrame({"x": x}), tmp_path / "sub" / "t.csv")
    back = [float(v) for v in path.read_text().splitlines()[1:]]
    assert back == x


def test_fmt_coef_matches_the_decision_text_format():
    c = Coef("log_wage", 4.395154698336432, 2.2, 0.07110034176756663, 8.719209054905297,
             0.046367973450909504, 387)
    as_dict = {"name": c.name, "estimate": c.estimate, "se": c.se, "ci_low": c.ci_low,
               "ci_high": c.ci_high, "p": c.p, "df": c.df}
    assert common.fmt_coef(as_dict) == _coef_lines([c])
