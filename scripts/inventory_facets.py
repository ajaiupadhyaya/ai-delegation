"""Inventory of the facet-layout AEI files (releases r3-r5).

Writes docs/audit/tables/facet_inventory.md: for each release and source, every distinct
(facet, level, variable) with its row count and three example `cluster_name`s.
AEI data are conversations matched to O*NET tasks; this table describes coverage only.

Run: uv run python scripts/inventory_facets.py
"""

from pathlib import Path

import duckdb

from aideleg.acquire.sources import by_key
from aideleg.config import RAW, ROOT

OUT = ROOT / "docs/audit/tables/facet_inventory.md"
RELEASES = ("r3", "r4", "r5")
SOURCES = (("claude_ai", "claude_ai"), ("1p_api", "api"))


def _cell(s: str | None) -> str:
    if s is None:
        return "(null)"
    base, sep, tail = s.rpartition("::") if "::" in s else (s, "", "")
    if len(base) > 50:
        base = base[:47] + "..."
    s = f"{base}{sep}{tail}"
    return s.replace("|", "\\|")


def inventory(path: Path) -> list[tuple]:
    sql = f"""
        SELECT facet, level, variable, count(*) AS n,
               list(DISTINCT cluster_name ORDER BY cluster_name)[1:3] AS ex
        FROM read_csv('{path}', all_varchar=true, delim=',', quote='"', escape='"')
        GROUP BY facet, level, variable
        ORDER BY facet, level, variable
    """
    return duckdb.connect().sql(sql).fetchall()


def main() -> None:
    lines = [
        "# Facet inventory, AEI releases r3-r5",
        "",
        "Generated by `scripts/inventory_facets.py` from the raw files. One row per distinct",
        "`(facet, level, variable)` in each file, with its row count and up to three example",
        "`cluster_name`s (sorted; task or request text truncated to 50 characters with any",
        "`::suffix` kept; `(null)` = empty).",
        "Every `(facet, variable)` here must be mapped or ignored in",
        "`src/aideleg/aei/metric_map.csv` (tested).",
        "",
        "| release | source | facet | level | variable | rows | example cluster_name |",
        "|---|---|---|---|---|---|---|",
    ]
    for rel in RELEASES:
        for source, key in SOURCES:
            path = RAW / by_key(f"aei_{rel}_{key}").dest
            for facet, level, variable, n, ex in inventory(path):
                exs = "; ".join(_cell(e) for e in ex) if ex else "(null)"
                lines.append(f"| {rel} | {source} | {facet} | {level} | {variable} | {n} | {exs} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines) - 11} rows)")


if __name__ == "__main__":
    main()
