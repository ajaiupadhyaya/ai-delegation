"""Regenerate the GENERATED blocks of PAP §9 from the files (never typed by hand).

    uv run python scripts/pap_freeze.py

- MANIFEST table: every key of data/raw/MANIFEST.json; each raw file's SHA-256 is recomputed on
  disk and must equal the recorded one; the SHA-256 of MANIFEST.json itself and the key count.
- Code binding: `git rev-parse HEAD` and `git rev-parse HEAD:src/aideleg/confirm_h5.py`; the
  working-tree file must hash to the same blob, and the tree must be clean in src/.
- Frozen values: the "Frozen values" list of docs/pap/power.md, copied verbatim.

Reads no market data beyond hashing the frozen files' bytes.
"""

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAP = ROOT / "docs/pap/pre-analysis-plan.md"
MANIFEST = ROOT / "data/raw/MANIFEST.json"
POWER = ROOT / "docs/pap/power.md"
SCRIPT = "src/aideleg/confirm_h5.py"


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True,
                          check=True).stdout.strip()


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def manifest_block() -> str:
    m = json.loads(MANIFEST.read_text())
    rows = []
    for key in sorted(m):
        e = m[key]
        on_disk = sha256(ROOT / "data/raw" / e["dest"])
        if on_disk != e["sha256"]:
            sys.exit(f"{key}: on-disk SHA-256 {on_disk} != MANIFEST {e['sha256']}")
        rows.append(f"| `{key}` | `{e['dest']}` | {e['bytes']} | {e['retrieved_utc']} | "
                    f"`{e['sha256']}` |")
    head = [f"Generated by `scripts/pap_freeze.py` from `data/raw/MANIFEST.json`: "
            f"**{len(m)} keys**; "
            f"every file's SHA-256 recomputed on disk and equal to the recorded value. SHA-256 of "
            f"`MANIFEST.json` itself: `{sha256(MANIFEST)}`.",
            "",
            "| key | dest (under `data/raw/`) | bytes | retrieved (UTC) | SHA-256 |",
            "|---|---|---|---|---|"]
    return "\n".join(head + rows)


def code_block() -> str:
    if git("status", "--porcelain", "--", "src", "pyproject.toml", "uv.lock"):
        sys.exit("src/, pyproject.toml or uv.lock has uncommitted changes")
    head = git("rev-parse", "HEAD")
    subject = git("log", "-1", "--format=%s", head)
    blob = git("rev-parse", f"HEAD:{SCRIPT}")
    if git("hash-object", SCRIPT) != blob:
        sys.exit("confirm_h5.py on disk differs from HEAD")
    m = re.search(r'^PRIMARY_NULL: .*= "(\w+)"', (ROOT / SCRIPT).read_text(), re.M)
    return "\n".join([
        f"- Code commit the plan binds to: **`{head}`** (\"{subject}\"), from "
        f"`git rev-parse HEAD`.",
        f"- `{SCRIPT}` git blob: **`{blob}`** (`git rev-parse HEAD:{SCRIPT}`), with "
        f"`PRIMARY_NULL = \"{m.group(1) if m else '?'}\"`.",
    ])


def frozen_block() -> str:
    text = POWER.read_text()
    sec = text.split("## Frozen values", 1)[1].split("<!-- END GENERATED -->", 1)[0]
    lines = [ln for ln in sec.splitlines() if ln.startswith("- `")]
    if len(lines) < 30:
        sys.exit("Frozen values list not found in power.md")
    return "\n".join(lines)


def replace(text: str, name: str, body: str) -> str:
    pat = re.compile(rf"(<!-- BEGIN GENERATED: {re.escape(name)} -->\n).*?(<!-- END GENERATED: "
                     rf"{re.escape(name)} -->)", re.S)
    if not pat.search(text):
        sys.exit(f"block {name!r} not found in the PAP")
    return pat.sub(lambda mo: mo.group(1) + body + "\n" + mo.group(2), text)


def main() -> int:
    text = PAP.read_text()
    text = replace(text, "MANIFEST table", manifest_block())
    text = replace(text, "code binding", code_block())
    text = replace(text, "frozen values", frozen_block())
    PAP.write_text(text)
    print("PAP §9 blocks regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
