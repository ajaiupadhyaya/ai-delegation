"""Shared writers for generated results documents (PAP §0.2, spec §6).

- Every document starts with its generated-by line and states `WORDING` exactly once.
- No phrase in `FORBIDDEN_PHRASES` may appear outside `WORDING` (case-insensitive), and no table
  cell may carry significance stars.
- CSVs keep floats at full precision, so a number in a table equals its source value exactly.
"""

import re
from pathlib import Path

import polars as pl

WORDING = ("AEI data are conversations matched to O*NET tasks. Nothing here says anything about "
           "job risk, displacement or reassurance about the labour market.")
FORBIDDEN_PHRASES = ("job risk", "displacement", "job market", "reassur", "no effect",
                     "accountants use", "workers use")
_STARS = re.compile(r"\d\*+")


def generated_line(generator: str) -> str:
    return f"Generated by `{generator}`. Do not edit by hand."


def check_text(text: str) -> None:
    """Raise `ValueError` on a forbidden phrase outside `WORDING` or a starred table cell."""
    body = text.replace(WORDING, "")
    low = body.lower()
    found = [p for p in FORBIDDEN_PHRASES if p in low]
    if found:
        raise ValueError(f"forbidden phrase(s) {found} outside WORDING (spec §6, PAP §0.2)")
    for line in body.splitlines():
        if line.lstrip().startswith("|"):
            starred = [c.strip() for c in line.split("|") if _STARS.search(c)]
            if starred:
                raise ValueError(f"significance star(s) in table cell(s) {starred} (PAP §0.2)")


def write_result_doc(path: Path, title: str, generator: str,
                     sections: list[tuple[str, str]]) -> Path:
    """Write the generated-by line, the title, `WORDING`, then each `(heading, body)` section."""
    if any(WORDING in h or WORDING in b for h, b in sections):
        raise ValueError("WORDING appears in a section; the document states it once, up top")
    parts = [generated_line(generator), "", f"# {title}", "", WORDING]
    for heading, body in sections:
        parts += ["", f"## {heading}", "", body.rstrip("\n")]
    text = "\n".join(parts) + "\n"
    check_text(text)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def write_csv(df: pl.DataFrame, path: Path) -> Path:
    """Write `df` as CSV with floats at full (round-trip) precision."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.write_csv(path, float_precision=None)
    return path


def fmt_coef(c: dict) -> str:
    """One coefficient as the RQ1 decision texts print it (`family._coef_lines`)."""
    return (f"{c['name']} = {c['estimate']:.3f} (95% CI [{c['ci_low']:.3f}, {c['ci_high']:.3f}], "
            f"p = {c['p']:.4f})")
