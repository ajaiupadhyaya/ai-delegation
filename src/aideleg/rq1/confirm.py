class RefusedError(RuntimeError):
    """The runner refused before its marker: nothing was loaded and no attempt exists."""


@dataclass
class Inputs:
    panel: pl.DataFrame
    index: TaskIndex
    families: pl.DataFrame
    wages: pl.DataFrame
    oews_codes: set[str]
    soc_structure: pl.DataFrame | None
    gdp_country: pl.DataFrame
    wap_country: pl.DataFrame


def load_inputs() -> Inputs:
    """The study defaults: the §9.3 panel, the O*NET-SOC 2019 index, IWA families (D14), the
    OEWS May 2024 national wages and codes, the AEI SOC structure and the r3 GDP/WAP files."""
    gdp_key, wap_key = _INCOME_KEYS["country"]
    return Inputs(
        panel=pl.read_parquet(PANEL_PATH),
        index=default_index(),
        families=task_families("iwa"),
        wages=load_national_wages(2024),
        oews_codes=set(load_national(2024)["soc6"]),
        soc_structure=pl.read_csv(RAW / by_key("aei_soc_structure").dest),
        gdp_country=read_income_csv(RAW / by_key(gdp_key).dest),
        wap_country=read_income_csv(RAW / by_key(wap_key).dest),
    )


# --- refusals ------------------------------------------------------------------------------


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)


def check_clean(repo: Path = ROOT) -> str:
    """HEAD, or `RefusedError` unless the tag, ancestry and clean-tree conditions hold."""
    kind = _git(repo, "cat-file", "-t", f"refs/tags/{PAP_TAG}")
    if kind.returncode != 0 or kind.stdout.strip() != "tag":
        raise RefusedError(f"{PAP_TAG} is not an annotated tag in {repo}")
    if _git(repo, "merge-base", "--is-ancestor", PAP_TAG, "HEAD").returncode != 0:
        raise RefusedError(f"HEAD does not descend from {PAP_TAG}")
    status = _git(repo, "status", "--porcelain", "--untracked-files=all", "--", "src", "tests",
                  "pyproject.toml", "uv.lock")
    if status.returncode != 0 or status.stdout.strip():
        raise RefusedError("the tree is not clean under src, tests, pyproject.toml, uv.lock:\n"
                           + (status.stdout or status.stderr))
    head = _git(repo, "rev-parse", "HEAD")
    if head.returncode != 0:
        raise RefusedError("cannot resolve HEAD")
    return head.stdout.strip()


def _paths(out_dir: Path) -> dict[str, Path]:
    return {n: out_dir / n for n in (MARKER_NAME, JSON_NAME, MD_NAME, LOG_NAME)}


# --- scrambling and checks -----------------------------------------------------------------


def scramble_outcomes(panel: pl.DataFrame, seed: int) -> pl.DataFrame:
    """Every published OUTCOME_METRICS value replaced by U(0, 100) (`ai_autonomy_mean`:
    U(1, 5)). Null and NaN values stay as they are, so no row and no drop changes."""
    rng = np.random.default_rng(seed)
    n = panel.height
    pct, autonomy = rng.uniform(0, 100, n), rng.uniform(1, 5, n)
    published = (pl.col("metric").is_in(sorted(OUTCOME_METRICS)) & pl.col("value").is_not_null()
                 & ~pl.col("value").is_nan())
    return panel.with_columns(
        pl.when(published & (pl.col("metric") == "ai_autonomy_mean")).then(pl.Series(autonomy))
        .when(published).then(pl.Series(pct))
        .otherwise(pl.col("value")).alias("value"))


def definition_checks(panel: pl.DataFrame) -> dict[str, object]:
    """Renormalisation of the published patterns: the largest |Σ five patterns − 100| and
    |automation − (directive + feedback_loop)| over the cells that publish all of them, overall
    and by release, in the taxonomies H1–H4 read (`CHECKED_TAXONOMIES`). A cell is one
    (release, period, source, geography, taxonomy, level, node, definition). Identities of the
    measure only; no relation between variables."""
    key = ["release", "period_start", "source", "geo_level", "geo_id", "taxonomy", "level",
           "node_id", "definition"]
    m, v = pl.col("metric"), pl.col("value")
    cells = (panel.filter(m.is_in([*_PATTERNS, "automation_pct"]) & v.is_not_null()
                          & ~v.is_nan() & pl.col("taxonomy").is_in(CHECKED_TAXONOMIES))
             .group_by(key)
             .agg(n=m.filter(m.is_in(_PATTERNS)).n_unique(),
                  s=v.filter(m.is_in(_PATTERNS)).sum(),
                  a=v.filter(m == "automation_pct").first(),
                  d=v.filter(m.is_in(["directive_pct", "feedback_loop_pct"])).sum())
             .filter(pl.col("n") == 5))
    devs = cells.select("release", ds=(pl.col("s") - 100).abs(),
                        da=(pl.col("a") - pl.col("d")).abs())

    def mx(x) -> float | None:
        return None if x is None else float(x)

    by = devs.group_by("release").agg(pl.col("ds").max(), pl.col("da").max()).sort("release")
    return {"pattern_cells": cells.height,
            "pattern_sum_max_abs_dev": mx(devs["ds"].max()),
            "automation_bucket_max_abs_dev": mx(devs["da"].max()),
            "by_release": {r: {"pattern_sum": mx(a), "automation_bucket": mx(b)}
                           for r, a, b in by.iter_rows()}}


# --- serialisation -------------------------------------------------------------------------


def _tolerant(x):
    """Plain JSON values; a non-finite float becomes the string "NaN", "Infinity" or
    "-Infinity" (only used if `HypothesisResult.to_dict` refuses one)."""
    if isinstance(x, dict):
        return {str(k): _tolerant(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_tolerant(v) for v in x]
    if hasattr(x, "item") and not isinstance(x, (str, bytes)):
        x = x.item()
    if isinstance(x, float) and not math.isfinite(x):
        return "NaN" if math.isnan(x) else ("Infinity" if x > 0 else "-Infinity")
    return x


def _result_dict(res: HypothesisResult, log: logging.Logger) -> dict:
    try:
        return res.to_dict()
    except ValueError as e:
        log.warning("%s: %s; non-finite floats written as strings", res.hypothesis, e)
        return _tolerant(asdict(res))


def _sha256(path: Path) -> str | None:
    if not path.is_file():
        return None
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _blobs(repo: Path) -> dict[str, str | None]:
    out = {}
    for p in BOUND_FILES:
        r = _git(repo, "rev-parse", f"HEAD:{p}")
        out[p] = r.stdout.strip() if r.returncode == 0 else None
    return out


def _versions() -> dict[str, str]:
    return {"python": platform.python_version(),
            **{p: importlib.metadata.version(p) for p in VERSIONED}}


# --- report --------------------------------------------------------------------------------


def _fmt(x) -> str:
    if isinstance(x, float):
        return f"{x:.4f}"
    return str(x)


def _markdown(payload: dict) -> str:
    meta, results, decisions = payload["meta"], payload["results"], payload["decisions"]
    out = [GENERATED, "", "# RQ1 confirmatory results (P-RQ1 first run)", "", WORDING, ""]
    if meta["scrambled"]:
        out += [f"**DRY RUN: every outcome was SCRAMBLED (seed {meta['scramble_seed']}) before "
                "estimation. These numbers are not results.**", ""]
    out += [f"HEAD `{meta['head']}`; run at {meta['utc']} (UTC).", "", "## α split", "",
            SPLIT_STATEMENT, "", "## Decisions", ""]
    out += [f"- {decisions[h]['text']}" for h in ("H1", "H2", "H3", "H4")]
    out += ["", "## Coefficients", "",
            "| hypothesis | coefficient | estimate | 95% CI | p | df | P13 attenuation |",
            "|---|---|---|---|---|---|---|"]
    for h in ("H1", "H2", "H3", "H4"):
        diag = results[h]["diagnostics"]
        for c in results[h]["coefs"].values():
            df = "normal" if c["df"] is None else c["df"]
            att = diag.get(f"attenuation_{c['name']}")
            att = "—" if att is None else _fmt(att)
            out.append(f"| {h} | {c['name']} | {_fmt(c['estimate'])} | "
                       f"[{_fmt(c['ci_low'])}, {_fmt(c['ci_high'])}] | {_fmt(c['p'])} | {df} | "
                       f"{att} |")
    out += ["", "P13 attenuation: the between-task share of the regressor's identifying "
            "(within-IWA, FWL-residualised) variation, reported beside β_w (H1) and γ (H3) "
            "(PAP §4.1)."]
    out += ["", "## Samples and drops", "",
            "Drop shares are in percent of total r6 task usage (H1, H3); weights are not "
            "renormalised. H4 lists excluded countries by first failing reason.", ""]
    for h in ("H1", "H2", "H3", "H4"):
        r = results[h]
        sample = ", ".join(f"{k} = {v}" for k, v in r["sample"].items())
        out.append(f"- **{h}** ({r['outcome']}): {sample}")
        nodes = r["diagnostics"].get("structural_drop_nodes")
        if nodes:
            out.append("  - structural drop nodes: " + ", ".join(f"{k} = {v}"
                                                                 for k, v in nodes.items()))
        if r["drops"]:
            out.append("  - drops (%): " + ", ".join(f"{k} = {_fmt(v)}"
                                                    for k, v in r["drops"].items()))
    h2 = results["H2"]
    d2 = h2["diagnostics"]
    out += ["", "## H2 release-level inference", "",
            f"- Release-level wild bootstrap p = {_fmt(d2['p_wild'])} over "
            f"{d2['n_wild_draws']} Webb vectors (D22).",
            f"- Release-label randomisation p = {_fmt(d2['p_release_label'])} over "
            f"{d2['n_release_orderings']} orderings (descriptive only).", ""]
    out += [f"- {n}" for n in h2["notes"]]
    d4 = results["H4"]["diagnostics"]
    out += ["", "## H4 joint test", "",
            f"- Joint HC3 Wald F = {_fmt(d4['F'])} with ({d4['df_num']}, {d4['df_denom']}) df; "
            f"p = {_fmt(results['H4']['p_family'])}.", "", "## Non-PSD rule (PAP §4)", ""]
    psd = [f"- {h}: {n}" for h in ("H1", "H3") for n in results[h]["notes"]]
    out += psd or ["- The non-PSD rule was not applied to H1 or H3."]
    return "\n".join(out) + "\n"


# --- the run -------------------------------------------------------------------------------


def _logger(path: Path) -> tuple[logging.Logger, logging.Logger, list[logging.Handler]]:
    """(printing logger, file-only logger, handlers). The file is created with mode "x"."""
    fmt = logging.Formatter("%(asctime)s %(message)s", "%Y-%m-%dT%H:%M:%SZ")
    fmt.converter = time.gmtime
    file_h = logging.FileHandler(path, mode="x", encoding="utf-8")
    out_h = logging.StreamHandler(sys.stdout)
    for h in (file_h, out_h):
        h.setFormatter(fmt)
    log = logging.getLogger(_LOG)
    record = logging.getLogger(_LOG + ".record")
    for lg, hs in ((log, [file_h, out_h]), (record, [file_h])):
        lg.handlers = list(hs)
        lg.setLevel(logging.INFO)
        lg.propagate = False
    return log, record, [file_h, out_h]


def _write_x(path: Path, text: str) -> None:
    with open(path, "x", encoding="utf-8") as f:
        f.write(text)


def _fit(inputs: Inputs, log: logging.Logger) -> tuple[dict[str, HypothesisResult], dict]:
    panel, checks = inputs.panel, {}

    def timed(label, fn):
        t0 = time.perf_counter()
        out = fn()
        log.info("%s in %.2f s", label, time.perf_counter() - t0)
        return out

    tr = timed("H1/H3 rows built", lambda: build_task_rows(
        panel, inputs.index, inputs.families, inputs.wages, inputs.oews_codes,
        inputs.soc_structure))
    h1 = timed("H1 fitted", lambda: estimate_h1(tr))
    h3 = timed("H3 fitted", lambda: estimate_h3(tr))
    h2_panel = timed("H2 panel built", lambda: build_h2_panel(panel))
    w = h2_panel.group_by("task_node").agg(pl.col("weight").first())["weight"]
    checks["h2_nonpositive_weight_tasks"] = int((w.is_null() | (w <= 0)).sum())
    log.info("H2 panel: %d tasks, %d with weight <= 0 or null", w.len(),
             checks["h2_nonpositive_weight_tasks"])
    h2 = timed("H2 fitted", lambda: estimate_h2(h2_panel))
    geo = timed("H4 sample built", lambda: build_geo_sample(
        panel, gdp=inputs.gdp_country, wap=inputs.wap_country))
    h4 = timed("H4 fitted", lambda: estimate_h4(geo.frame))
    h4 = dataclasses.replace(
        h4, sample={**h4.sample, **{f"excluded_{k}": len(v) for k, v in geo.excluded.items()}},
        diagnostics={**h4.diagnostics, "excluded": geo.excluded,
                     "global_automation": geo.global_automation, "m_global": geo.m_global})
    results = {"H1": h1, "H2": h2, "H3": h3, "H4": h4}
    for h, r in results.items():
        log.info("%s sample: %s", h, json.dumps(_tolerant(r.sample)))
        log.info("%s drops: %s", h, json.dumps(_tolerant(r.drops)))
    return results, checks


def _timed_load(log: logging.Logger) -> Inputs:
    t0 = time.perf_counter()
    inputs = load_inputs()
    log.info("inputs loaded in %.2f s", time.perf_counter() - t0)
    return inputs


def run(out_dir: Path = OUT_DIR, *, scramble_seed: int | None = None,
        inputs: Inputs | None = None, repo: Path = ROOT) -> dict:
    """The single P-RQ1 run (module docstring). Returns the JSON payload."""
    head = check_clean(repo)
    out_dir = Path(out_dir)
    paths = _paths(out_dir)
    existing = [p.name for p in paths.values() if p.exists()]
    if existing:
        raise RefusedError(f"{out_dir} already holds {existing}: the run is write-once")
    if scramble_seed is not None and out_dir.resolve().is_relative_to(
            (ROOT / "docs/results").resolve()):
        raise RefusedError("a dry run never writes under docs/results")
    if scramble_seed is None and (inputs is not None
                                  or out_dir.resolve() != OUT_DIR.resolve()):
        raise RefusedError("a real run takes the study inputs and writes only to "
                           f"{OUT_DIR}; anything else is outside the P-RQ1 protocol")
    panel_sha = _sha256(PANEL_PATH)
    if scramble_seed is None and panel_sha != PAP_PANEL_SHA256:
        raise RefusedError(f"{PANEL_PATH} has SHA-256 {panel_sha}, not the PAP §9.3 value "
                           f"{PAP_PANEL_SHA256}")
    blobs, versions = _blobs(repo), _versions()
    pap = _git(repo, "rev-parse", f"{PAP_TAG}^{{commit}}")
    pap_commit = pap.stdout.strip() if pap.returncode == 0 else None

    out_dir.mkdir(parents=True, exist_ok=True)
    utc = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    _write_x(paths[MARKER_NAME], f"{utc}\n{head}\n")
    log: logging.Logger | None = None
    handlers: list[logging.Handler] = []
    t_start = time.perf_counter()
    try:
        log, record, handlers = _logger(paths[LOG_NAME])
        log.info("P-RQ1 run at %s, HEAD %s, scrambled=%s", utc, head, scramble_seed is not None)
        source = "load_inputs" if inputs is None else "supplied"
        inputs = _timed_load(log) if inputs is None else inputs
        checks = definition_checks(inputs.panel)
        log.info("definition checks: %s", json.dumps(checks))
        if scramble_seed is not None:
            inputs = dataclasses.replace(inputs,
                                         panel=scramble_outcomes(inputs.panel, scramble_seed))
            log.info("outcomes scrambled with seed %d before any estimator", scramble_seed)
        results, fit_checks = _fit(inputs, log)
        checks.update(fit_checks)

        meta = {"utc": utc, "head": head, "pap_v1_commit": pap_commit, "blobs": blobs,
                "versions": versions, "seed": SEED, "scrambled": scramble_seed is not None,
                "scramble_seed": scramble_seed, "inputs": source,
                "input_sha256": {str(PANEL_PATH.relative_to(ROOT)): panel_sha,
                                 str(MANIFEST_PATH.relative_to(ROOT)): _sha256(MANIFEST_PATH)},
                "panel_sha256_equals_pap": panel_sha == PAP_PANEL_SHA256,
                "checks": checks}
        alpha = {"H2": H2_ALPHA, "family": FAMILY_ALPHA, "members": list(RQ1_FAMILY),
                 "statement": SPLIT_STATEMENT}
        result_dicts = {h: _result_dict(r, log) for h, r in results.items()}
        record.info("%s%s", RESULTS_LOG_PREFIX, json.dumps(result_dicts, allow_nan=False))

        decisions = {h: asdict(d) for h, d in decide(results).items()}
        payload = {"meta": meta, "alpha": alpha, "results": result_dicts,
                   "decisions": decisions}
        text = json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
        _write_x(paths[JSON_NAME], text)
        _write_x(paths[MD_NAME], _markdown(payload))
        log.info("run completed in %.2f s", time.perf_counter() - t_start)
        return json.loads(text)
    except BaseException:
        tb = traceback.format_exc()
        if log is not None:
            log.error("run failed after the marker (an attempt, not a result):\n%s", tb)
        mode = "a" if paths[MD_NAME].exists() else "x"
        with open(paths[MD_NAME], mode, encoding="utf-8") as f:
            f.write(f"{GENERATED}\n\n# P-RQ1 attempt: failed after the marker\n\n"
                    f"HEAD `{head}`; marker at {utc} (UTC).\n\n```\n{tb}```\n")
        raise
    finally:
        for h in handlers:
            h.close()
        for name in (_LOG, _LOG + ".record"):
            logging.getLogger(name).handlers = []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="aideleg.rq1.confirm", description=(
        "The single P-RQ1 run of H1-H4 (write-once). --dry-run DIR scrambles every outcome "
        "first and writes to DIR, never under docs/results."))
    ap.add_argument("--dry-run", type=Path, default=None, metavar="DIR")
    a = ap.parse_args(argv)
    try:
        if a.dry_run is None:
            run(OUT_DIR)
            print(f"P-RQ1 run written to {OUT_DIR}")
            return 0
        t0 = time.perf_counter()
        payload = run(a.dry_run, scramble_seed=SEED)
    except RefusedError as e:
        print(f"refused: {e}", file=sys.stderr)
        return 2
    print("dry run (scrambled outcomes): coverage only")
    for h in ("H1", "H2", "H3", "H4"):
        r = payload["results"][h]
        print(f"{h} sample: {json.dumps(r['sample'])}")
        print(f"{h} drops: {json.dumps(r['drops'])}")
    print(f"checks: {json.dumps(payload['meta']['checks'])}")
    print(f"dry run completed without exception in {time.perf_counter() - t0:.1f} s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
