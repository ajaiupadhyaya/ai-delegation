"""The write-once RQ1 runner (PAP §0.5 P-RQ1, §4, D22): the single logged first run of H1–H4.

AEI data are conversations matched to O*NET tasks. Nothing here says anything about workers,
jobs or the labour market.

Protocol (each step completes before the next)
1. `check_clean`: `pap-v1` is an annotated tag, HEAD descends from it, and `git status
   --porcelain --untracked-files=all -- src tests pyproject.toml uv.lock` is empty.
2. Refuse (`RefusedError`) if the attempt marker or any output exists in `out_dir`. A dry run
   (`scramble_seed` set) also refuses an `out_dir` inside `docs/results`; a real run refuses
   supplied `inputs`, any `out_dir` other than `OUT_DIR`, and a panel parquet whose SHA-256
   is not the PAP §9.3 value.
3. The bound blobs and library versions are recorded, then the marker is created with
   exclusive creation (UTC time and HEAD). **Only then** are the inputs loaded.
4. From the marker on, any exception writes its traceback to `confirmatory_rq1.md` and is
   re-raised: the run is then an attempt, not a result (§0.5). The log is streamed to
   `confirmatory_rq1.log` from the marker on, so it survives a crash.
5. A dry run replaces every published outcome (`OUTCOME_METRICS`) by a uniform draw before any
   estimator sees it (`scramble_outcomes`). It adds and removes no rows, so its samples and drops
   equal the real run's.
6. H1, H3 (`build_task_rows`), H2 (`build_h2_panel`) and H4 (`build_geo_sample`) are fitted
   with their PAP defaults. Every result is serialised and written to the log **before**
   `decide` is called, so a decision-layer failure cannot lose the estimates.
7. The JSON, the markdown report and the log are written with exclusive creation; nothing is
   ever overwritten.

Bound code. `BOUND_FILES` are frozen at the first real run: `tests/rq1/test_frozen.py` checks
their blobs and the numpy, scipy, polars and statsmodels versions against the JSON's `meta`.
`pyproject.toml` and `uv.lock` are not bound by blob, so later plans can add unrelated
dependencies; later plans put new code in new modules and never edit a bound file.
"""

