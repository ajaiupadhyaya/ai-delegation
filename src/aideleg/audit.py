def unpublished_mass(panel: pl.DataFrame) -> tuple[pl.DataFrame, pl.DataFrame]:
    """(global, by geo level): 100 minus the published `pct` sum per taxonomy group."""
    grp = ["release", "source", "period_start", "geo_level", "geo_id", "taxonomy", "level"]
    s = (panel.filter(pl.col("metric") == "pct").group_by(grp)
         .agg(n_nodes=pl.len(), published=pl.col("value").sum())
         .with_columns(unpublished=(100 - pl.col("published")).clip(lower_bound=0)))
    glob = (s.filter(pl.col("geo_level") == "global")
            .select("release", "source", "period_start", "taxonomy", "level", "n_nodes",
                    "published", "unpublished")
            .sort("release", "source", "period_start", "taxonomy", "level"))
    geo = (s.filter(pl.col("geo_level") != "global")
           .group_by("release", "geo_level", "taxonomy")
           .agg(groups=pl.len(), mean_unpublished=pl.col("unpublished").mean(),
                max_unpublished=pl.col("unpublished").max())
           .sort("release", "geo_level", "taxonomy"))
    return glob, geo


def _task_wide(panel: pl.DataFrame) -> pl.DataFrame:
    keep = ["pct", "automation_pct", *PATTERNS, "filtered_pct", "none_pct",
            "not_classified_pct"]
    t = panel.filter((pl.col("taxonomy") == "onet_task") & (pl.col("geo_level") == "global")
                     & pl.col("metric").is_in(keep)
                     & ~pl.col("node_id").str.starts_with("unmatched:"))
    w = t.pivot(on="metric", index=["release", "source", "period_start", "node_id"],
                values="value", aggregate_function=None)
    return w.with_columns(pl.lit(None, pl.Float64).alias(c) for c in keep
                          if c not in w.columns)


def _wauto(a: pl.DataFrame) -> float | None:
    """pct-weighted mean task automation_pct (None when there is no weight)."""
    return (a["pct"] * a["automation_pct"]).sum() / a["pct"].sum() if a.height else None


def task_collab_suppression(panel: pl.DataFrame) -> pl.DataFrame:
    """Per release x source x period: how complete task x collaboration publication is, and
    the usage-weighted task automation (renormalised over published patterns) next to the
    release's overall automation figure."""
    from aideleg.occupations import SUPPRESSION

    w = _task_wide(panel)
    overall = (panel.filter((pl.col("taxonomy") == "overall")
                            & (pl.col("geo_level") == "global")
                            & (pl.col("metric") == "automation_pct"))
               .select("release", "source", "period_start", overall_automation="value"))
    n5 = pl.sum_horizontal([pl.col(p).is_not_null().cast(pl.Int64) for p in PATTERNS])
    rows = []
    for (rel, src, ps), g in w.group_by("release", "source", "period_start"):
        g = g.with_columns(n5=n5)
        comps = SUPPRESSION.get(rel)
        if comps:
            supp = pl.when(pl.all_horizontal([pl.col(c).is_not_null() for c in comps])).then(
                pl.sum_horizontal(comps))
        else:
            supp = pl.lit(None, pl.Float64)
        g = g.with_columns(supp=supp)
        a = g.filter(pl.col("automation_pct").is_not_null() & pl.col("pct").is_not_null())
        s = g.filter(pl.col("supp").is_not_null() & pl.col("pct").is_not_null())
        has_p = g.filter(pl.col("pct").is_not_null())
        rows.append({
            "release": rel, "source": src, "period_start": ps,
            "tasks": has_p.height,
            "with_any_pattern": int((g["n5"] > 0).sum()),
            "with_all_five": int((g["n5"] == 5).sum()),
            "all_five_pct": (100 * int((g["n5"] == 5).sum()) / has_p.height
                             if has_p.height else None),
            "weighted_suppressed_pct": ((s["pct"] * s["supp"]).sum() / s["pct"].sum()
                                        if s.height else None),
            "weighted_task_automation": _wauto(a),
            "auto_all_five_tasks": _wauto(a.filter(pl.col("n5") == 5)),
            "auto_partial_tasks": _wauto(a.filter(pl.col("n5") < 5)),
            "partial_tasks_pct_mass": (100 * a.filter(pl.col("n5") < 5)["pct"].sum()
                                       / a["pct"].sum() if a.height else None),
        })
    out = pl.DataFrame(rows, schema_overrides={"period_start": pl.Date}).join(
        overall, on=["release", "source", "period_start"], how="left")
    return out.with_columns(
        gap=pl.col("weighted_task_automation") - pl.col("overall_automation")
    ).sort("release", "source", "period_start")


def bounds_occupation(occ: dict[str, pl.DataFrame]) -> pl.DataFrame:
    """Per release x source x period: usage-weighted mean occupation automation_pct,
    suppressed_pct and the R7 bounds, and the median occupation width ub - lb."""
    rows = []
    for rel, t in occ.items():
        for (src, ps), g in t.group_by("source", "period_start"):
            def wm(c: str, g=g) -> float | None:
                h = g.filter(pl.col(c).is_not_null())
                return (h["usage_share"] * h[c]).sum() / h["usage_share"].sum() \
                    if h.height and h["usage_share"].sum() > 0 else None
            width = (g["automation_share_all_ub"] - g["automation_share_all_lb"]).drop_nulls()
            rows.append({"release": rel, "source": src, "period_start": ps,
                         "basis": g["basis"][0], "occupations": g.height,
                         "automation_pct": wm("automation_pct"),
                         "suppressed_pct": wm("suppressed_pct"),
                         "lb": wm("automation_share_all_lb"),
                         "ub": wm("automation_share_all_ub"),
                         "median_width": width.median() if width.len() else None})
    return pl.DataFrame(rows, schema_overrides={"period_start": pl.Date}).sort(
        "release", "source", "period_start")


def bounds_ff49(exposure: pl.DataFrame) -> pl.DataFrame:
    """Per design: correlation across FF49 of z_delegation with its R7 bounds (the same
    AEI quantity under two treatments of suppressed conversations)."""
    rows = []
    for d in sorted(exposure["design"].unique()):
        e = exposure.filter(pl.col("design") == d)
        for b in ("z_delegation_lb", "z_delegation_ub"):
            ok = e.filter(pl.col(b).is_not_null() & pl.col("z_delegation").is_not_null())
            rows.append({
                "design": d, "bound": b, "n": ok.height,
                "pearson": ok.select(pl.corr("z_delegation", b)).item() if ok.height > 2
                else None,
                "spearman": ok.select(pl.corr("z_delegation", b, method="spearman")).item()
                if ok.height > 2 else None})
    return pl.DataFrame(rows, schema_overrides={"pearson": pl.Float64, "spearman": pl.Float64})


