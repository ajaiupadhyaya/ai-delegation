def releases_table(panel: pl.DataFrame) -> pl.DataFrame:
    """One row per release x source x period: window, geographies, taxonomies, rows."""
    g = panel.group_by("release", "source", "period_start", "period_end").agg(
        rows=pl.len(),
        geo_levels=pl.col("geo_level").unique().sort(),
        taxonomies=pl.col("taxonomy").filter(pl.col("geo_level") == "global").unique().sort(),
        metrics=pl.col("metric").n_unique(),
        artifact_metrics=pl.col("metric").filter(pl.col("metric").str.starts_with("artifact_"))
        .n_unique(),
    ).sort("release", "source", "period_start")
    return g.with_columns(
        published=pl.col("release").replace_strict({k: str(v) for k, v in RELEASES.items()}),
        window=pl.when(pl.col("release").is_in(list(DEFAULT_WINDOW)))
        .then(pl.lit("DEFAULT (README states none)")).otherwise(pl.lit("as published")),
    ).select("release", "published", "source", "period_start", "period_end", "window",
             "geo_levels", "taxonomies", "metrics", "artifact_metrics", "rows")


def regimes_table(panel: pl.DataFrame) -> pl.DataFrame:
    """release x source: platform, classifier, collaboration taxonomy, suppression, basis."""
    d = panel.group_by("release", "source").agg(pl.col("definition").unique().sort())
    rows = []
    for rel, src, defs in d.sort("release", "source").iter_rows():
        tax = sorted({x.split("|")[0] for x in defs})
        plat = sorted({x.split("|", 1)[1] for x in defs if "|" in x})
        if plat:
            platform = "; ".join(plat)
            pdoc = f"aei/{rel}/data_documentation.md"
            cite = _cite(pdoc, plat[0] if src == "claude_ai" else '"1P API"')
        elif (rel, src) in PLATFORM_NOTE:
            platform, cite = PLATFORM_NOTE[(rel, src)]
        elif rel == "r6":
            needle = "`claude_ai`" if src == "claude_ai" else "`1p_api`"
            line = _doc_line(R6_DOC, f"| {needle} |") or ""
            cells = [c.strip() for c in line.strip("|").split("|")]
            platform = cells[2] if len(cells) > 2 else "see documentation"
            cite = _cite(R6_DOC, f"| {needle} |")
        else:
            platform, cite = "not stated", "—"
        rows.append({
            "release": rel, "source": src, "platform_scope": platform,
            "platform_source": cite,
            "classifier_model": "not stated in release files",
            "collab_taxonomy": ", ".join(tax),
            "suppression_construct": SUPPRESSION_CONSTRUCT[rel],
            "occupation_basis": ("published SOC (soc_detailed)" if rel == "r6"
                                 else "task-derived (O*NET tasks -> SOC)"),
        })
    return pl.DataFrame(rows)


