"""Data audit: coverage tables for the pre-analysis plan, written to `docs/audit/tables/`.

AEI data are conversations matched to O*NET tasks. Every table here describes coverage,
counts, measurement regimes, or the distribution of a single variable. Nothing here says
anything about job risk or displacement in the labour market.

Integrity constraint (global constraints; no hypothesis testing before `pap-v1`): this module
computes NO relationship between a delegation measure and any occupation, task or geography
covariate of hypotheses H1-H4, and reads no market data. The only correlations computed
are (a) between two constructions of the same AEI quantity (allocated vs published r6
usage; delegation vs its R7 bounds) and (b) the descriptive "could vs does" rank
correlation between AEI exposure and the theoretical benchmarks across FF49 (RQ2,
`benchmarks.rank_correlations`). The OEWS national file is reduced to `soc6, title,
tot_emp` on load. `tests/test_audit.py` checks the source for forbidden names.

Every number in the tables is computed here from `data/raw` and `data/derived`; the only
hand-written content is categorical regime metadata (platform wording for r1/r2, which
their data files do not state), each with its source named in the table.

Run: `make audit` (`python -m aideleg.audit`).
"""

