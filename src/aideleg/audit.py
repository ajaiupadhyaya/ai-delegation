def r6_bucket_consistency(panel: pl.DataFrame) -> pl.DataFrame:
    """r6 nodes with all five patterns: published automation vs renormalised directive +
    feedback_loop, per source and month."""
    from aideleg.aei.panel import _pattern_sums

    p = _pattern_sums(panel.filter(pl.col("release") == "r6")).filter(
        pl.col("auto").is_not_null())
    p = p.with_columns(gap=(pl.col("auto") - pl.col("dfl") / pl.col("s5") * 100).abs())
    by = p.group_by("source", "period_start").agg(
        nodes=pl.len(), max_gap=pl.col("gap").max(), mean_gap=pl.col("gap").mean(),
        over_1pt=(pl.col("gap") > 1.0).sum())
    allr = p.select(source=pl.lit("all"), period_start=pl.lit(None, pl.Date), nodes=pl.len(),
                    max_gap=pl.col("gap").max(), mean_gap=pl.col("gap").mean(),
                    over_1pt=(pl.col("gap") > 1.0).sum())
    return pl.concat([by.sort("source", "period_start"),
                      allr.cast(by.schema)])


def r6_allocated_vs_published(pub: pl.DataFrame, alloc: pl.DataFrame) -> pl.DataFrame:
    """Rank correlation of r6 occupation usage_share, task-allocated vs published SOC, per
    source and month (inner join on soc6), with the codes found on one side only."""
    key = ["period_start", "source", "soc6"]
    rows = []
    for (ps, src), a in pub.group_by("period_start", "source"):
        b = alloc.filter((pl.col("period_start") == ps) & (pl.col("source") == src))
        j = a.select(*key, pub=pl.col("usage_share"), pub_a=pl.col("automation_pct")).join(
            b.select(*key, alloc=pl.col("usage_share"), alloc_a=pl.col("automation_pct")),
            on=key, how="inner")
        ja = j.filter(pl.col("pub_a").is_not_null() & pl.col("alloc_a").is_not_null())
        rows.append({
            "month": ps.strftime("%Y-%m"), "source": src,
            "rho_usage": j.select(pl.corr("pub", "alloc", method="spearman")).item(),
            "pearson_usage": j.select(pl.corr("pub", "alloc")).item(),
            "rho_automation": ja.select(pl.corr("pub_a", "alloc_a", method="spearman")).item(),
            "n_joined": j.height,
            "only_published": a.join(b, on="soc6", how="anti").height,
            "only_allocated": b.join(a, on="soc6", how="anti").height})
    return pl.DataFrame(rows).sort("month", "source")


def r6_only_occupations(occ: dict[str, pl.DataFrame], source: str = "claude_ai"
                        ) -> tuple[pl.DataFrame, pl.DataFrame]:
    """(summary, list): soc6 codes in the r6 published table that no r2-r5 task-derived
    table has, and their mean (over months) r6 usage_share."""
    earlier = set()
    for r in ("r2", "r3", "r4", "r5"):
        earlier |= set(occ[r].filter(pl.col("source") == source)["soc6"])
    r6 = occ["r6"].filter(pl.col("source") == source)
    n_months = r6["period_start"].n_unique()
    use = r6.group_by("soc6").agg(usage=pl.col("usage_share").sum() / n_months)
    only = use.filter(~pl.col("soc6").is_in(list(earlier))).sort("usage", descending=True)
    summary = pl.DataFrame({"source": [source], "r6_occupations": [use.height],
                            "r6_only": [only.height],
                            "r6_only_usage_pct": [only["usage"].sum()]})
    return summary, only.head(10)


