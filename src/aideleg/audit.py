def metric_availability(panel: pl.DataFrame) -> pl.DataFrame:
    """metric x release: the global taxonomies publishing it (`—` = never published)."""
    g = (panel.filter(pl.col("geo_level") == "global")
         .group_by("metric", "release").agg(pl.col("taxonomy").unique().sort()))
    rels = sorted(RELEASES)
    rows = []
    present = {(m, r): t for m, r, t in g.iter_rows()}
    for m in AVAILABILITY_METRICS:
        row: dict[str, str] = {"metric": m}
        for r in rels:
            t = present.get((m, r))
            row[r] = ", ".join(_TAX_ABBR.get(x, x) for x in t) if t else "—"
        rows.append(row)
    art = {r: g.filter((pl.col("release") == r)
                       & pl.col("metric").str.starts_with("artifact_"))["metric"].n_unique()
           for r in rels}
    rows.append({"metric": "artifact_*_pct (count)",
                 **{r: (str(art[r]) if art[r] else "—") for r in rels}})
    return pl.DataFrame(rows)


def task_definition_stability(panel: pl.DataFrame) -> pl.DataFrame:
    """For each task-level collaboration metric: releases publishing it at task level, and
    the denominator it is defined over in each."""
    t = panel.filter((pl.col("taxonomy") == "onet_task") & (pl.col("geo_level") == "global"))
    have = t.group_by("metric").agg(pl.col("release").unique().sort())
    denom = {
        "automation_pct": "five classified patterns (renormalised)",
        "augmentation_pct": "five classified patterns (renormalised)",
        "filtered_pct": "all conversations of the task (r2 only)",
        "none_pct": "all conversations of the task",
        "not_classified_pct": "all conversations of the task; holds suppressed cells",
        "ai_autonomy_mean": "classified conversations of the task (1-5 scale)",
    }
    for p in PATTERNS:
        denom[p] = "five classified patterns (renormalised)"
    rows = []
    for m in [*PATTERNS, "automation_pct", "augmentation_pct", "filtered_pct", "none_pct",
              "not_classified_pct", "ai_autonomy_mean"]:
        rel = have.filter(pl.col("metric") == m)["release"]
        rels = rel[0].to_list() if rel.len() else []
        rows.append({"metric": m, "task_level_releases": rels, "n_releases": len(rels),
                     "denominator": denom[m]})
    return pl.DataFrame(rows, schema={"metric": pl.String,
                                      "task_level_releases": pl.List(pl.String),
                                      "n_releases": pl.Int64, "denominator": pl.String})


