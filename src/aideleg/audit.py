def task_matching(panel: pl.DataFrame, index, legacy=None) -> pl.DataFrame:
    """Per release x source: global onet_task nodes, sentinels, unmatched text, match rate,
    and statements carrying more than one O*NET Task ID under the study index and (when
    given) under `legacy`, the r2-era task file alone (the Task 4 index)."""
    t = panel.filter((pl.col("taxonomy") == "onet_task") & (pl.col("geo_level") == "global")
                     & (pl.col("metric") == "pct"))
    nodes = t.group_by("release", "source", "node_id").agg(
        name=pl.col("node_name").first(), mass=pl.col("value").sum(),
        periods=pl.col("period_start").n_unique())
    per = t.group_by("release", "source").agg(n_periods=pl.col("period_start").n_unique())
    names = nodes["name"].unique().drop_nulls().to_list()
    ncand = {n: len(index.task_ids_for(n)) for n in names}
    lcand = ({n: len(legacy.task_ids_for(n)) for n in names} if legacy is not None
             else dict.fromkeys(names, 0))
    nodes = nodes.with_columns(
        n_cand=pl.col("name").replace_strict(ncand, default=0, return_dtype=pl.Int64),
        n_legacy=pl.col("name").replace_strict(lcand, default=0, return_dtype=pl.Int64),
        sentinel=pl.col("node_id").is_in(list(SENTINELS)),
        unmatched=pl.col("node_id").str.starts_with("unmatched:")
        & ~pl.col("node_id").is_in(list(SENTINELS)))
    out = nodes.group_by("release", "source").agg(
        nodes=pl.len(),
        sentinel_nodes=pl.col("sentinel").sum(),
        sentinel_mass=pl.col("mass").filter(pl.col("sentinel")).sum(),
        unmatched_nodes=pl.col("unmatched").sum(),
        unmatched_mass=pl.col("mass").filter(pl.col("unmatched")).sum(),
        multi_candidate=(pl.col("n_cand") > 1).filter(~pl.col("sentinel")).sum(),
        multi_candidate_legacy=(pl.col("n_legacy") > 1).filter(~pl.col("sentinel")).sum(),
    ).join(per, on=["release", "source"]).with_columns(
        sentinel_mass_pct=pl.col("sentinel_mass") / pl.col("n_periods"),
        unmatched_mass_pct=pl.col("unmatched_mass") / pl.col("n_periods"),
        match_rate_pct=100 * (pl.col("nodes") - pl.col("sentinel_nodes")
                              - pl.col("unmatched_nodes"))
        / (pl.col("nodes") - pl.col("sentinel_nodes")),
    ).sort("release", "source")
    return out.select("release", "source", "n_periods", "nodes", "sentinel_nodes",
                      "sentinel_mass_pct", "unmatched_nodes", "unmatched_mass_pct",
                      "match_rate_pct", "multi_candidate", "multi_candidate_legacy")


