# --- markdown -------------------------------------------------------------------------

def _fmt(v: object, digits: int) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.{digits}f}"
    if isinstance(v, list):
        return ", ".join(str(x) for x in v) if v else "—"
    return str(v).replace("|", "/")


def md_table(df: pl.DataFrame, digits: int | dict[str, int] = 2) -> str:
    """A markdown table; floats rounded to `digits` (per column if a dict), null as `—`."""
    cols = df.columns
    dig = {c: (digits.get(c, 2) if isinstance(digits, dict) else digits) for c in cols}
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.iter_rows():
        lines.append("| " + " | ".join(_fmt(v, dig[c]) for c, v in zip(cols, row,
                                                                          strict=True)) + " |")
    return "\n".join(lines)


def write_doc(name: str, title: str, sections: list[tuple[str, str]],
              out: Path = TABLES) -> Path:
    """Write `out/<name>.md`: title, provenance, wording rule, then (heading, body) pairs."""
    out.mkdir(parents=True, exist_ok=True)
    parts = [f"# {title}", "",
             "Generated by `python -m aideleg.audit` (`make audit`) from `data/raw` and "
             "`data/derived`. Do not edit by hand.", "", WORDING, ""]
    for heading, body in sections:
        if heading:
            parts += [f"## {heading}", ""]
        parts += [body, ""]
    path = out / f"{name}.md"
    path.write_text("\n".join(parts))
    return path


def _cite(rel: str, needle: str) -> str:
    """`data/raw/<rel>:<line>` of the first line containing `needle`, else the file alone."""
    path = RAW / rel
    if path.exists():
        for i, line in enumerate(path.read_text().splitlines(), 1):
            if needle in line:
                return f"data/raw/{rel}:{i}"
    return f"data/raw/{rel}"


def _doc_line(rel: str, needle: str) -> str | None:
    path = RAW / rel
    if not path.exists():
        return None
    for line in path.read_text().splitlines():
        if needle in line:
            return line
    return None


