"""Generated table and figure includes for the paper (Plan 4 Task 18).

`docs/paper/tables.csv` (`id, source, caption, notes`) names a committed results table: `source`
is a repo-relative markdown file, with `#<n>` for its n-th pipe table (1-based) when it holds more
than one. `build_tables` writes `docs/paper/_generated/tables/<id>.md`: the source table lines
unchanged (no number is reformatted), then the caption line `: <caption> {#tbl-<id>}`, then the
notes. `docs/paper/figures.csv` (`id, stem, caption, alt`) names a figure in
`docs/paper/figures/`; `build_figures` writes `docs/paper/_generated/figures/<id>.md` with the
PDF for the PDF format and the PNG for HTML, each block labelled `{#fig-<id>}` once.

Captions, notes and alt texts hold no typed numeral (Task 19 scans them); a number a caption needs
is a `{{< var >}}` shortcode. Paths in the includes are relative to `docs/paper`, where Quarto
renders the documents that include them. A build removes stale includes from its directory.

AEI data are conversations matched to O*NET tasks.
"""

import csv
import json
import re
from pathlib import Path

from aideleg import paplog
from aideleg.config import ROOT

PAPER = ROOT / "docs/paper"
TABLES = PAPER / "tables.csv"
FIGURES = PAPER / "figures.csv"
GENERATED = PAPER / "_generated"
TABLE_COLUMNS = ["id", "source", "caption", "notes"]
FIGURE_COLUMNS = ["id", "stem", "caption", "alt"]
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
HEADER = "<!-- Generated by `uv run python -m aideleg.paper` from `docs/paper/{}`. Do not edit. -->"


def tables_in(text: str) -> list[list[str]]:
    """Every pipe table of a markdown text: runs of consecutive lines starting with `|` whose
    second line is a delimiter row, as their lines unchanged."""
    out, run = [], []
    for line in text.splitlines() + [""]:
        if line.startswith("|"):
            run.append(line)
            continue
        if len(run) >= 2 and re.fullmatch(r"\|(\s*:?-{3,}:?\s*\|)+", run[1].strip()):
            out.append(run)
        run = []
    return out


def extract_table(text: str, n: int | None) -> list[str]:
    """The `n`-th pipe table (1-based); with `n` None the text must hold exactly one."""
    found = tables_in(text)
    if n is None:
        if len(found) != 1:
            raise ValueError(f"{len(found)} tables in the source; name one with #<n>")
        return found[0]
    if not 1 <= n <= len(found):
        raise ValueError(f"table #{n} requested, the source has {len(found)}")
    return found[n - 1]


def _rows(path: Path, columns: list[str]) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != columns:
            raise ValueError(f"{path}: columns {reader.fieldnames}, expected {columns}")
        rows = list(reader)
    ids = [r["id"] for r in rows]
    bad = [i for i in ids if not ID_RE.match(i)]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if bad or dup:
        raise ValueError(f"{path.name}: bad ids {bad}, duplicate ids {dup}")
    return rows


def _write_all(out_dir: Path, texts: dict[str, str]) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("*.md"):
        if stale.stem not in texts:
            stale.unlink()
    paths = []
    for name, text in texts.items():
        p = out_dir / f"{name}.md"
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
        paths.append(p)
    return paths


def build_tables(tables_csv: Path = TABLES, out_dir: Path = GENERATED / "tables") -> list[Path]:
    texts = {}
    for row in _rows(tables_csv, TABLE_COLUMNS):
        path, _, n = row["source"].partition("#")
        src = ROOT / path
        try:
            table = extract_table(src.read_text(encoding="utf-8"), int(n) if n else None)
        except (OSError, ValueError) as e:
            raise ValueError(f"table {row['id']}: {row['source']}: {e}") from None
        parts = [
            HEADER.format(tables_csv.name),
            "",
            *table,
            "",
            f": {row['caption']} {{#tbl-{row['id']}}}",
        ]
        if row["notes"].strip():
            parts += ["", row["notes"].strip()]
        texts[row["id"]] = "\n".join(parts) + "\n"
    return _write_all(out_dir, texts)


def _attr(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def build_figures(figures_csv: Path = FIGURES, out_dir: Path = GENERATED / "figures") -> list[Path]:
    texts = {}
    for row in _rows(figures_csv, FIGURE_COLUMNS):
        blocks = [HEADER.format(figures_csv.name)]
        for fmt, ext in (("pdf", "pdf"), ("html", "png")):
            img = PAPER / "figures" / f"{row['stem']}.{ext}"
            if not img.is_file():
                raise ValueError(f"figure {row['id']}: no {img.relative_to(ROOT)}")
            blocks += [
                "",
                f'::: {{.content-visible when-format="{fmt}"}}',
                f"![{row['caption']}](figures/{row['stem']}.{ext})"
                f'{{#fig-{row["id"]} fig-alt="{_attr(row["alt"])}"}}',
                ":::",
            ]
        texts[row["id"]] = "\n".join(blocks) + "\n"
    return _write_all(out_dir, texts)


# --- generated appendices (Plan 4 Task 21) -----------------------------------------------------
#
# Each builder writes `docs/paper/_generated/appendix/<name>.md`, which `docs/paper/appendix/*.qmd`
# includes. Text quoted from the PAP, the robustness files and `post-freeze.md` is copied
# unchanged; the robustness files only have their headings demoted one level (they sit under the
# appendix heading) and their links to sibling row files pointed at the row's heading here. Wide
# tables are set landscape and small for the PDF (raw LaTeX, which HTML ignores).

PAP_MD = ROOT / "docs/pap/pre-analysis-plan.md"
POST_FREEZE = ROOT / "docs/disclosures/post-freeze.md"
ROBUSTNESS = ROOT / "docs/results/robustness"
APPENDIX = GENERATED / "appendix"
MANIFEST_JSON = ROOT / "data/raw/MANIFEST.json"
MAKEFILE = ROOT / "Makefile"
UV_LOCK = ROOT / "uv.lock"
PYPROJECT = ROOT / "pyproject.toml"
PYTHON_VERSION = ROOT / ".python-version"
CODE_BINDING = ("<!-- BEGIN GENERATED: code binding -->", "<!-- END GENERATED: code binding -->")
LANDSCAPE = (
    "```{=latex}\n\\begin{landscape}\\scriptsize\\raggedright\n```",
    "```{=latex}\n\\end{landscape}\n```",
)
# verbatim PAP text holding long hashes and URLs: a smaller size in the PDF only
SMALL = (
    "```{=latex}\n\\begingroup\\footnotesize\\raggedright\n```",
    "```{=latex}\n\\endgroup\n```",
)
KINDS = {
    "Addition": "addition",
    "Addition (set)": "addition",
    "Clarification": "clarification",
    "Deviation": "deviation",
}
_RESULTS_SEEN = re.compile(r"^- Results seen: (.*)$", re.M)
_DELIM = re.compile(r"\|(\s*:?-{3,}:?\s*\|)+")


def _rel(p: Path) -> str:
    p = Path(p).resolve()
    return str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else p.name


def _appendix_header(*sources: Path | str) -> str:
    names = ", ".join(f"`{s if isinstance(s, str) else _rel(s)}`" for s in sources)
    return f"<!-- Generated by `uv run python -m aideleg.paper` from {names}. Do not edit. -->"


def _write_one(out_dir: Path, name: str, text: str) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"{name}.md"
    if not p.exists() or p.read_text(encoding="utf-8") != text:
        p.write_text(text, encoding="utf-8")
    return p


def section_body(text: str, heading: str) -> str:
    """The lines after the exact `heading` line, up to the next heading of the same or a higher
    level (blank lines at both ends removed)."""
    lines = text.split("\n")
    if heading not in lines:
        raise ValueError(f"heading {heading!r} not found")
    i = lines.index(heading)
    level = len(heading) - len(heading.lstrip("#"))
    stop = re.compile(rf"^#{{1,{level}}} ")
    j = next((k for k in range(i + 1, len(lines)) if stop.match(lines[k])), len(lines))
    return "\n".join(lines[i + 1 : j]).strip("\n")


def _cell(s: str) -> str:
    return s.replace("|", "\\|").strip()


def preregistration_appendix(pap: Path = PAP_MD, *, out_dir: Path = APPENDIX) -> Path:
    """PAP §0.1 (signature), the tag and its commit, the §0.3 decision register table and the
    §9.2 code binding block, each verbatim."""
    from aideleg.paper.variables import pap_values

    text = Path(pap).read_text(encoding="utf-8")
    register = extract_table(section_body(text, "### 0.3 Decision register"), None)
    begin, end = CODE_BINDING
    if begin not in text or end not in text:
        raise ValueError(f"{pap}: no §9.2 code binding block")
    binding = text.split(begin + "\n", 1)[1].split(end, 1)[0].strip("\n")
    pv = pap_values()
    parts = [
        _appendix_header(pap),
        "",
        SMALL[0],
        "",
        "## Signature (PAP §0.1)",
        "",
        section_body(text, "### 0.1 Signature"),
        "",
        f"The signed plan is the git tag `{pv['tag']}`, an annotated tag on commit "
        f"`{pv['commit']}` ({pv['date']}). Every later change to the plan is an entry of PAP §11 "
        "(appendix: Deviations).",
        "",
        "## Decision register (PAP §0.3)",
        "",
        *register,
        "",
        "## Code binding (PAP §9.2)",
        "",
        binding,
        "",
        SMALL[1],
    ]
    return _write_one(out_dir, "preregistration", "\n".join(parts) + "\n")


def _entry_rows(pap: Path) -> list[str]:
    rows = ["| id | kind | date | results seen |", "|----|------|-----|--------------------|"]
    for e in paplog.entries(pap):
        m = _RESULTS_SEEN.search(e["body"])
        seen = m[1].strip() if m else "not stated"
        rows.append(f"| {e['kind']}-{e['n']} | {KINDS[e['form']]} | {e['date']} | {_cell(seen)} |")
    return rows


def deviations_appendix(pap: Path = PAP_MD, *, out_dir: Path = APPENDIX) -> Path:
    """A summary table of every §11 entry, §11's body verbatim, then §10 verbatim."""
    text = Path(pap).read_text(encoding="utf-8")
    body = "\n".join(paplog.section_11_lines(text)[1:]).strip("\n")
    has_entries = any(ln.startswith("### ") for ln in body.split("\n"))
    parts = [_appendix_header(pap), "", "## Summary of the PAP §11 entries", ""]
    if has_entries:
        parts += [
            "One row per entry of PAP §11, in document order: additions under D20 (`A-`), "
            "clarifications (`C-`) and deviations (`D-`), with the entry's date and its "
            '"Results seen" field as written ("not stated" where the entry has none).',
            "",
            *_entry_rows(pap),
        ]
    else:
        parts.append("None at freeze, and none since.")
    parts += [
        "",
        SMALL[0],
        "",
        "## PAP §11, verbatim",
        "",
        body,
        "",
        "## PAP §10: corrections to the design spec, verbatim",
        "",
        section_body(text, "## 10. Corrections to the design spec"),
        "",
        SMALL[1],
    ]
    return _write_one(out_dir, "deviations", "\n".join(parts) + "\n")


def disclosures_appendix(
    pap: Path = PAP_MD, post: Path = POST_FREEZE, *, out_dir: Path = APPENDIX
) -> Path:
    """PAP §0.4 verbatim, then `docs/disclosures/post-freeze.md` verbatim."""
    text = Path(pap).read_text(encoding="utf-8")
    parts = [
        _appendix_header(pap, post),
        "",
        "## Before the freeze (PAP §0.4)",
        "",
        section_body(text, "### 0.4 Disclosures"),
        "",
        Path(post).read_text(encoding="utf-8").strip("\n"),
    ]
    return _write_one(out_dir, "disclosures", "\n".join(parts) + "\n")


def _row_anchor(name: str) -> str:
    return f"app-rob-{Path(name).stem.lower().replace('_', '-')}"


def _robustness_text(name: str, src: str) -> list[str]:
    out, fenced, first = [], False, True
    for line in src.rstrip("\n").split("\n"):
        if line.startswith("```"):
            fenced = not fenced
        if not fenced and re.match(r"^#{1,5} ", line):
            line = "#" + line
            if first:
                line += f" {{#{_row_anchor(name)}}}"
                first = False
        line = re.sub(
            r"\]\(((?:R\d\d|summary|implementation_choices)\.md)\)",
            lambda m: f"](#{_row_anchor(m[1])})",
            line,
        )
        out.append(line)
    return out


def robustness_appendix(robustness: Path = ROBUSTNESS, *, out_dir: Path = APPENDIX) -> Path:
    """`summary.md`, `implementation_choices.md` and every `R<nn>.md` in row order. In the PDF
    the whole appendix is set landscape and small so the wide tables fit; HTML is unchanged."""
    robustness = Path(robustness)
    names = ["summary.md", "implementation_choices.md"]
    names += sorted(p.name for p in robustness.glob("R[0-9][0-9].md"))
    parts = [_appendix_header(robustness), "", LANDSCAPE[0]]
    for name in names:
        parts += ["", *_robustness_text(name, (robustness / name).read_text(encoding="utf-8"))]
    parts += ["", LANDSCAPE[1]]
    return _write_one(out_dir, "robustness", "\n".join(parts) + "\n")


def _manifest_status(manifest: dict, pap: Path) -> dict[str, str]:
    """For every non-set key and each set source: "frozen at `pap-v1`" or "added under D20 (A-n,
    ...)", from the §11 additions. Where git has the tag, the frozen keys must be exactly those
    in the tag's MANIFEST."""
    from aideleg.paper import variables

    added: dict[str, list[str]] = {}
    for e in paplog.entries(pap):
        if e["kind"] == "A":
            added.setdefault(e["title"].strip("`"), []).append(f"A-{e['n']}")
    status = {}
    keys = [k for k in manifest if not paplog.is_set_source(k)] + ["sec_fts/"]
    if paplog.SET_INDEX_KEY in manifest:
        keys.append(paplog.SET_INDEX_KEY)
    for k in keys:
        status[k] = (
            f"added under D20 ({', '.join(added[k])})" if k in added else "frozen at `pap-v1`"
        )
    if variables._has_history(ROOT):
        tagged = variables._git(ROOT, "show", f"{variables.PAP_TAG}:data/raw/MANIFEST.json")
        if tagged is not None:
            at_tag = set(json.loads(tagged))
            for k in keys:
                in_tag = (
                    any(t == k or t.startswith(k) for t in at_tag)
                    if k.endswith("/")
                    else (k in at_tag)
                )
                if in_tag == (k in added):
                    raise ValueError(
                        f"{k}: in the {variables.PAP_TAG} MANIFEST = {in_tag}, "
                        f"§11 addition = {k in added}"
                    )
    return status


def _docs_index_count(manifest: dict, pap: Path, raw: Path) -> int:
    rec = manifest[paplog.SET_INDEX_KEY]
    logged = [
        paplog.set_entry_fields(e)
        for e in paplog.entries(pap)
        if e["form"] == "Addition (set)" and e["title"].strip("`") == paplog.SET_INDEX_KEY
    ]
    logged = [f["count"] for f in logged if f["digest"] == rec["sha256"]]
    path = Path(raw) / rec.get("dest", paplog.SET_INDEX_FILE)
    if path.is_file():
        n = paplog.set_stats(paplog.SET_INDEX_KEY, manifest, raw)["count"]
        if logged and logged[-1] != n:
            raise ValueError(f"{path}: {n} lines, §11 logs {logged[-1]}")
        return n
    if not logged:
        raise ValueError(f"no {path} and no §11 set entry with the MANIFEST's SHA-256")
    return logged[-1]


def _manifest_table(manifest: dict, pap: Path, raw: Path) -> tuple[list[str], list[str]]:
    status = _manifest_status(manifest, pap)
    rows = [
        "| key | URL | retrieved (UTC) | bytes | SHA-256 (first 16) | status |",
        "|----|----------|----|---|----|----|",
    ]
    notes = []
    fts_done = False
    for key in sorted(manifest):
        rec = manifest[key]
        if key.startswith("sec_fts/"):
            if fts_done:
                continue
            fts_done = True
            s = paplog.set_stats("sec_fts/", manifest, raw)
            nbytes = sum(manifest[k]["bytes"] for k in s["keys"])
            rows.append(
                f"| `sec_fts/` | EDGAR full-text search, {s['count']} records "
                f"(<https://efts.sec.gov/LATEST/search-index>) | {s['first']} to {s['last']} | "
                f"{nbytes} | set digest {s['digest'][:16]} | {status['sec_fts/']} |"
            )
            notes.append(
                f"- `sec_fts/`: {s['count']} records; set digest (`paplog.set_digest`, SHA-256 of "
                f"the sorted `<key> <sha256>` lines) `{s['digest']}`."
            )
            continue
        if key == paplog.SET_INDEX_KEY:
            n = _docs_index_count(manifest, pap, raw)
            rows.append(
                f"| `{key}` | SEC EDGAR 10-K primary documents, {n} documents "
                f"(<{rec['url']}>) | {rec['retrieved_utc']} | {rec['bytes']} | "
                f"{rec['sha256'][:16]} | {status[key]} |"
            )
            notes.append(
                f"- `{key}`: {n} documents; SHA-256 of `{rec.get('dest', paplog.SET_INDEX_FILE)}` "
                f"`{rec['sha256']}`."
            )
            continue
        rows.append(
            f"| `{key}` | <{rec['url']}> | {rec['retrieved_utc']} | {rec['bytes']} | "
            f"{rec['sha256'][:16]} | {status[key]} |"
        )
    return rows, notes


def _environment() -> list[str]:
    import tomllib

    lock = tomllib.loads(UV_LOCK.read_text(encoding="utf-8"))
    project = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))
    versions: dict[str, list[str]] = {}
    for pkg in lock["package"]:
        versions.setdefault(pkg["name"], []).append(pkg["version"])

    def name(req: str) -> str:
        return re.split(r"[\s<>=!~\[;]", req, maxsplit=1)[0].lower()

    groups = [("runtime", project["project"].get("dependencies", []))]
    groups += [(g, reqs) for g, reqs in project.get("dependency-groups", {}).items()]
    python = (
        PYTHON_VERSION.read_text(encoding="utf-8").strip()
        if PYTHON_VERSION.is_file()
        else lock.get("requires-python", "")
    )
    rows = [
        f"Python {python} (`.python-version`; `uv.lock` requires-python "
        f"`{lock.get('requires-python', '')}`), with every direct dependency at its `uv.lock` "
        "version:",
        "",
        "| package | version | group |",
        "|---|---|---|",
    ]
    for group, reqs in groups:
        for req in reqs:
            n = name(req)
            if n not in versions:
                raise ValueError(f"{n}: a direct dependency missing from uv.lock")
            rows.append(f"| `{n}` | {', '.join(sorted(set(versions[n])))} | {group} |")
    return rows


def make_targets(makefile: Path = MAKEFILE) -> list[tuple[str, list[str], list[str]]]:
    """(target, prerequisites, recipe lines) for every rule of the Makefile, in file order, with
    simple `:=`/`=` variables expanded; special targets (`.PHONY`, ...) are skipped."""
    raw = Path(makefile).read_text(encoding="utf-8").split("\n")
    lines: list[str] = []
    for line in raw:
        if lines and lines[-1].endswith("\\"):
            lines[-1] = lines[-1][:-1].rstrip() + " " + line.strip()
        else:
            lines.append(line)
    var_re = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*:?=\s*(.*)$")
    rule_re = re.compile(r"^([^\s:#=][^:#=]*?)\s*:(?![=])\s*(.*)$")
    variables_: dict[str, str] = {}
    rules: list[tuple[str, list[str], list[str]]] = []
    current: tuple[str, list[str], list[str]] | None = None

    def expand(s: str) -> str:
        return re.sub(r"\$\(([A-Za-z_][A-Za-z0-9_]*)\)", lambda m: variables_.get(m[1], m[0]), s)

    for line in lines:
        if line.startswith("\t"):
            if current is not None:
                current[2].append(line.strip())
            continue
        current = None
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = var_re.match(line)
        if m:
            variables_[m[1]] = m[2].strip()
            continue
        m = rule_re.match(line)
        if m is None:
            continue
        prereqs = re.findall(r"\$\([^)]*\)|\S+", expand(m[2]))
        for t in m[1].split():
            if not t.startswith("."):
                current = (t, prereqs, [])
                rules.append(current)
    return rules


def _dag_rows(makefile: Path = MAKEFILE) -> list[str]:
    rows = ["| target | depends on | runs |", "|----|------|------|"]
    for target, prereqs, recipe in make_targets(makefile):
        dep = ", ".join(f"`{p}`" for p in prereqs) or "nothing"
        run = "; ".join(f"`{_cell(r.lstrip('@'))}`" for r in recipe) or "its prerequisites only"
        rows.append(f"| `{target}` | {_cell(dep)} | {run} |")
    return rows


