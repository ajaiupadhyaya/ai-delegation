"""Post-result influence diagnostics (PAP §11 D-3): exploratory; not a decision.

Added after every confirmatory, Plan 3 and Plan 4 result and the Task 16 red-team findings had
been seen (D-3, approved by Ajai in chat, 2026-10-24). Nothing here changes a confirmatory or
committed estimate, a hypothesis decision or a robustness row; every number is a sensitivity of
a committed headline, reported once and never selected.

- **H1** (`h1_influence`): Plan 2's `estimate_h1` on the primary task rows (`upstream.task_rows`:
  r6, claude_ai, IWA families), leaving out each SOC major group (the first two digits of the
  row's soc6) in turn, then the single top occupation and the top 3 occupations by weight. The
  ranking weight is the D13 row weight summed per soc6 over the rows that enter H1 (automation
  share, education and log wage all present, the null-or-NaN rule of `estimate_h1`); shares
  are in percent of that sample's weight. Rows are removed, never re-weighted.
- **H2** (`h2_influence`): Plan 2's `estimate_h2` on the primary balanced panel
  (`upstream.h2_panel()`), leaving out each release in turn; the same tasks and fixed task
  weights. β, the task-clustered p and the release-level wild bootstrap p are as Plan 2
  returns them. The balancing count compares the tasks and usage of `h2_panel(balanced=False)`
  (tasks with a value in at least two releases, R22's frame) with the balanced panel.
- **H6** (`h6_influence`): the 2024 talk index T against Design B `z_usage` across FF49
  industries (Plan 3's `talk_table`, `t_index`, `gap`, `spearman_ci`), leaving out each
  industry in turn. The primary carries a nominal, exploratory two-sided p by the standard
  t-approximation for Spearman's rho, t = rho·sqrt((n − 2)/(1 − rho²)) on n − 2 df.

AEI data are conversations matched to O*NET tasks.
"""

import dataclasses
import math
