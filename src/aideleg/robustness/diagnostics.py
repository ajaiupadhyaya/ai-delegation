def _header(title: str, notes: list[str]) -> list[str]:
    return [
        f"# {title}: {TAG}",
        "",
        f"Generated by `{GENERATOR}`. Do not edit by hand.",
        "",
        f"Label: {LABEL}. Added after the results were seen (PAP §11 D-3); no confirmatory or "
        "committed estimate changes, and no row below is counted, selected or read as a test "
        "of a hypothesis.",
        "",
        "## Notes",
        "",
        *[f"- {n}" for n in notes],
        "",
        "## Results",
        "",
    ]


def _finish(lines: list[str]) -> str:
    text = "\n".join([*lines, "", upstream.WORDING, ""])
    check_text(text)
    return text


def _close(a: float, b: float) -> bool:
    return math.isclose(a, b, rel_tol=REL_TOL, abs_tol=1e-12)


# --- H1 ------------------------------------------------------------------------------------


def h1_sample_weights(tr: upstream.TaskRows) -> pl.DataFrame:
    """`soc6, weight, share_pct` over the rows that enter H1, heaviest first (ties by code)."""
    rows = tr.rows
    for c in (H1_OUTCOME, *H1_PREDICTORS):
        ok = pl.col(c).is_not_null()
        if rows.schema[c].is_float():
            ok = ok & ~pl.col(c).is_nan()
        rows = rows.filter(ok)
    total = float(rows["weight"].sum())
    return (
        rows.group_by("soc6")
        .agg(pl.col("weight").sum())
        .with_columns((pl.col("weight") / total * 100).alias("share_pct"))
        .sort(["weight", "soc6"], descending=[True, False])
    )


def _h1_record(part: str, dropped: str, share: float, res) -> dict:
    e, w = (res.coefs[p] for p in H1_PREDICTORS)
    return {
        "part": part,
        "dropped": dropped,
        "dropped_weight_pct": share,
        "n_rows": int(res.sample["n_rows"]),
        "n_tasks": int(res.sample["n_tasks"]),
        "n_occ": int(res.sample["n_occ"]),
        "beta_e": e.estimate,
        "se_e": e.se,
        "p_e": e.p,
        "beta_w": w.estimate,
        "se_w": w.se,
        "p_w": w.p,
        "p_H1": res.p_family,
    }


def h1_influence(tr: upstream.TaskRows, estimate=None) -> pl.DataFrame:
    """The primary H1 fit, then one fit per left-out SOC major group and per top-k set."""
    estimate = upstream.estimate_h1 if estimate is None else estimate
    weights = h1_sample_weights(tr)
    share = dict(zip(weights["soc6"].to_list(), weights["share_pct"].to_list(), strict=True))

    def without(codes: set[str]) -> upstream.TaskRows:
        return dataclasses.replace(tr, rows=tr.rows.filter(~pl.col("soc6").is_in(sorted(codes))))

    recs = [_h1_record("primary", "none", 0.0, estimate(tr))]
    for major in sorted({s[:2] for s in tr.rows["soc6"].to_list()}):
        codes = {s for s in tr.rows["soc6"].unique().to_list() if s[:2] == major}
        drop = sum(share.get(s, 0.0) for s in codes)
        recs.append(_h1_record("leave_out_soc_major", major, drop, estimate(without(codes))))
    order = weights["soc6"].to_list()
    for k in TOP_K:
        codes = order[:k]
        drop = sum(share[s] for s in codes)
        recs.append(
            _h1_record(f"leave_out_top_{k}", ", ".join(codes), drop, estimate(without(set(codes))))
        )
    return pl.DataFrame(recs, schema_overrides={"dropped_weight_pct": pl.Float64}).select(
        H1_COLUMNS
    )


