# --- runners -------------------------------------------------------------------------------


def _write(df: pl.DataFrame, text: str, stem: str, out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    csv_path, md_path = out_dir / f"{stem}.csv", out_dir / f"{stem}.md"
    write_csv(df, csv_path)
    md_path.write_text(text, encoding="utf-8")
    return csv_path, md_path


def run_h1(out_dir: Path = OUT_DIR) -> tuple[Path, Path]:
    guards.require_rq1_run_committed()
    df = h1_influence(upstream.task_rows())
    want = upstream.committed_rq1()["results"]["H1"]
    p = df.row(0, named=True)
    for col, name in (("beta_e", H1_PREDICTORS[0]), ("beta_w", H1_PREDICTORS[1])):
        if not _close(p[col], float(want["coefs"][name]["estimate"])):
            raise AssertionError(f"H1 primary {col} does not reproduce the committed record")
    if not _close(p["p_H1"], float(want["p_family"])):
        raise AssertionError("H1 primary p_H1 does not reproduce the committed record")
    return _write(df, h1_md(df), "h1_influence", Path(out_dir))


def run_h2(out_dir: Path = OUT_DIR) -> tuple[Path, Path]:
    guards.require_rq1_run_committed()
    df = h2_influence(upstream.h2_panel(), upstream.h2_panel(balanced=False))
    want = upstream.committed_rq1()["results"]["H2"]
    p = df.row(0, named=True)
    if not (
        _close(p["beta"], float(want["coefs"]["trend"]["estimate"]))
        and _close(p["p_wild"], float(want["diagnostics"]["p_wild"]))
    ):
        raise AssertionError("H2 primary does not reproduce the committed record")
    return _write(df, h2_md(df), "h2_influence", Path(out_dir))


def primary_gap() -> pl.DataFrame:
    """Plan 3's primary gap frame, rebuilt as `h6.talk.run_talk` builds it."""
    filers = upstream.load_filers()
    hits = pl.read_parquet(upstream.FTS_HITS)
    t = upstream.talk_table(upstream.numerator(hits, filers), upstream.denominator(filers))
    expo_b = upstream.exposures().filter(pl.col("design") == "B").select("ff49_short", "z_usage")
    return upstream.gap(upstream.t_index(t), expo_b)


def run_h6(out_dir: Path = OUT_DIR) -> tuple[Path, Path]:
    guards.require_confirmatory_committed()
    df = h6_influence(primary_gap())
    p = df.row(0, named=True)
    printed = f"| {fmt_rho(p['rho'])} | [{fmt_rho(p['ci_lo'])}, {fmt_rho(p['ci_hi'])}] |"
    if printed not in (upstream.H6_DIR / "gap.md").read_text(encoding="utf-8"):
        raise AssertionError("H6 primary Spearman does not reproduce docs/results/h6/gap.md")
    return _write(df, h6_md(df), "h6_influence", Path(out_dir))


def write_all(out_dir: Path = OUT_DIR) -> list[Path]:
    """Write the three D-3 diagnostics; return their paths."""
    out: list[Path] = []
    for run in (run_h1, run_h2, run_h6):
        out += run(Path(out_dir))
    return out
