# --- H2 ------------------------------------------------------------------------------------


def _h2_record(part: str, dropped: str, panel: pl.DataFrame, estimate) -> dict:
    releases = sorted(set(panel["release"].to_list()), key=upstream.H2_RELEASES.index)
    rec = {
        "part": part,
        "dropped": dropped,
        "releases": " ".join(releases),
        "n_tasks": panel["task_node"].n_unique(),
        "n_rows": panel.height,
        "usage_share_pct": None,
        "beta": None,
        "se": None,
        "p_cluster": None,
        "p_wild": None,
        "n_wild_draws": None,
        "note": "",
    }
    try:
        res = estimate(panel)
    except (ValueError, ArithmeticError, np.linalg.LinAlgError) as exc:
        rec["note"] = f"undefined: {exc}"
        return rec
    c = res.coefs["trend"]
    n_draws = int(res.diagnostics["n_wild_draws"])
    rec |= {
        "beta": c.estimate,
        "se": c.se,
        "p_cluster": c.p,
        "p_wild": float(res.diagnostics["p_wild"]),
        "n_wild_draws": n_draws,
        "note": f"smallest attainable wild bootstrap p = 6/{n_draws}",
    }
    return rec


def h2_influence(balanced: pl.DataFrame, unbalanced: pl.DataFrame, estimate=None) -> pl.DataFrame:
    """The primary H2 fit, one fit per left-out release, and the balancing count."""
    estimate = upstream.estimate_h2 if estimate is None else estimate
    recs = [_h2_record("primary", "none", balanced, estimate)]
    for r in sorted(set(balanced["release"].to_list()), key=upstream.H2_RELEASES.index):
        recs.append(
            _h2_record("leave_out_release", r, balanced.filter(pl.col("release") != r), estimate)
        )
    kept = set(balanced["task_node"].unique().to_list())
    w = unbalanced.group_by("task_node").agg(pl.col("weight").first())
    total = float(w["weight"].sum())
    gone = unbalanced.filter(~pl.col("task_node").is_in(sorted(kept)))
    gone_w = float(w.filter(~pl.col("task_node").is_in(sorted(kept)))["weight"].sum())
    n_unb = unbalanced["task_node"].n_unique()
    recs.append(
        {
            "part": "balancing_removed",
            "dropped": "tasks with a value in some but not all of the releases",
            "releases": " ".join(
                sorted(set(unbalanced["release"].to_list()), key=upstream.H2_RELEASES.index)
            ),
            "n_tasks": gone["task_node"].n_unique(),
            "n_rows": gone.height,
            "usage_share_pct": gone_w / total * 100 if total else None,
            "beta": None,
            "se": None,
            "p_cluster": None,
            "p_wild": None,
            "n_wild_draws": None,
            "note": (
                f"of {n_unb} tasks and {unbalanced.height} rows in build_h2_panel(balanced=False); "
                "usage share = their fixed task weight in percent of that panel's task weight"
            ),
        }
    )
    schema = {
        "usage_share_pct": pl.Float64,
        "beta": pl.Float64,
        "se": pl.Float64,
        "p_cluster": pl.Float64,
        "p_wild": pl.Float64,
        "n_wild_draws": pl.Int64,
    }
    return pl.DataFrame(recs, schema_overrides=schema).select(H2_COLUMNS)


