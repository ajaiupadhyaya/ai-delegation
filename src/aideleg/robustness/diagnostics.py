# --- H6 ------------------------------------------------------------------------------------


def spearman_p_nominal(rho: float, n: int) -> float:
    """Two-sided p of Spearman's rho by the t-approximation on n − 2 df (nominal)."""
    if n < 3:
        raise ValueError(f"need at least 3 pairs, got {n}")
    if abs(rho) >= 1:
        return 0.0
    t = rho * math.sqrt((n - 2) / (1 - rho * rho))
    return float(2 * stats.t.sf(abs(t), n - 2))


def h6_influence(g: pl.DataFrame) -> pl.DataFrame:
    """The primary Spearman (T, z_usage) with its nominal p, then one per left-out industry."""
    names = g["ff49_short"].to_list()
    x, y = g["T"].to_numpy().astype(float), g["z_usage"].to_numpy().astype(float)

    def rec(part: str, dropped: str, keep: np.ndarray, with_p: bool) -> dict:
        sp = upstream.spearman_ci(x[keep], y[keep])
        lo, hi = sp["ci95"]
        return {
            "part": part,
            "dropped": dropped,
            "n": int(sp["n"]),
            "rho": sp["rho"],
            "ci_lo": float(lo),
            "ci_hi": float(hi),
            "p_nominal": spearman_p_nominal(sp["rho"], int(sp["n"])) if with_p else None,
            "p_method": P_METHOD if with_p else "",
        }

    all_ = np.ones(len(names), dtype=bool)
    recs = [rec("primary", "none", all_, True)]
    for i in sorted(range(len(names)), key=lambda j: names[j]):
        keep = all_.copy()
        keep[i] = False
        recs.append(rec("leave_out_industry", names[i], keep, False))
    return pl.DataFrame(recs, schema_overrides={"p_nominal": pl.Float64}).select(H6_COLUMNS)


